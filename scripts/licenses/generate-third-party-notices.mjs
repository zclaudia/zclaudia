// 按生产依赖精确版本收集真实许可文本，生成 THIRD-PARTY-NOTICES.md。
// 与 ZCode 原版的差异：本仓库暂无 Electron/Node 运行时、原生搜索工具等内嵌组件，
// 相应的分节与输入哈希机器未移植；copiedComponents 改从人工维护的
// third-party/inventory.json 读取（登记未来从 ZCode 等上游搬入的源码/资产）。
// 生成文件不入库（.gitignore），尾部附机器可读清单供 `licenses.mjs check` 判断新鲜度。
import { readFile, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { collectNpmNotices, hashBytes } from './third-party-npm.mjs';
import {
  MANIFEST_FOOTER,
  MANIFEST_HEADER,
  noticesFileName,
  repositoryRoot,
  validateInventory,
} from './third-party-notices.mjs';

async function readOptionalJson(root, file) {
  try {
    return JSON.parse(await readFile(join(root, file), 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }
}

export async function generateThirdPartyNotices(root = repositoryRoot) {
  const overrides = await readOptionalJson(root, 'third-party/npm-overrides.json');
  const inventory = JSON.parse(await readFile(join(root, 'third-party/inventory.json'), 'utf8'));
  validateInventory(inventory);
  // copiedComponents 的 roots 必须真实存在：登记了搬入源码却不包含其路径，说明登记过期。
  for (const component of inventory.copiedComponents) {
    for (const dir of component.roots) {
      if (!(await stat(join(root, dir))).isDirectory())
        throw new Error(`Copied component root missing: ${component.id} → ${dir}`);
    }
  }
  const { packages } = await collectNpmNotices(root, overrides);
  const currentPackages = new Set(packages.map(item => `${item.name}@${item.version}`));
  for (const record of overrides) {
    if (!currentPackages.has(record.package))
      throw new Error(`Stale npm notice override: ${record.package}`);
  }
  const textRecords = new Map();
  function addText(bytes, owner, origin) {
    const sha256 = hashBytes(bytes);
    const record = textRecords.get(sha256) ?? { bytes, references: [] };
    record.references.push({ owner, origin });
    textRecords.set(sha256, record);
    return sha256;
  }
  const packageInventory = packages.map(({ notices, ...item }) => ({
    ...item,
    notices: notices.map(({ member, bytes }) => ({
      member,
      sha256: addText(bytes, `${item.name}@${item.version}`, member),
    })),
  }));
  const sections = [
    '# Third-party notices',
    'Generated by `node scripts/licenses.mjs notices` from the current workspace production dependency graph (exact installed versions, original license and notice text). This file is a generated artifact and is not tracked in git; regenerate it after dependency changes. The package list at the bottom is the machine-readable manifest consumed by `licenses.mjs check`.',
    'Original copyright, license and NOTICE text is retained below. Identical text is shared by the components listed above it. Package metadata license identifiers are descriptive; they do not replace the original terms. Copyright holders are never inferred from npm author fields.',
    '## npm packages',
    ...packageInventory.map(
      item =>
        `- ${item.name}@${item.version} — ${typeof item.license === 'string' ? item.license : JSON.stringify(item.license)}${item.acceptedMissingNotice ? `; ${item.acceptedMissingNotice}` : ''}`
    ),
  ];
  const evidence = overrides.filter(item => item.evidenceKind);
  if (evidence.length) {
    sections.push(
      '## Source evidence limitations',
      'Some publishers provide only a license identifier or a short README license section instead of a complete LICENSE file. For the following packages the supplied material explicitly identifies publisher metadata and standard terms; it is not represented as an original upstream LICENSE file. Any available README copyright notice is retained:',
      ...evidence.map(item => `- ${item.package}: ${item.source}`)
    );
  }
  if (inventory.copiedComponents.length) {
    sections.push(
      '## Copied source and assets',
      'Components whose source is copied into this repository. Each must carry the attribution header required by docs/development/third-party-licenses.md; local adaptations do not change the upstream terms.',
      ...inventory.copiedComponents.map(
        item =>
          `- ${item.id} (${item.license}): ${item.roots.join(', ')}. Source: ${item.source}. Copyright: ${item.copyright}.${item.notes ? ` Notes: ${item.notes}` : ''}`
      )
    );
  }
  sections.push('## License and NOTICE texts');
  for (const [sha256, record] of textRecords) {
    sections.push(
      `### Notice ${sha256}`,
      ...record.references.map(({ owner, origin }) => `- ${owner}: ${origin}`),
      '',
      '````text\n' + record.bytes.toString('utf8') + '\n````'
    );
  }
  const manifest = {
    schemaVersion: 1,
    packages: packages.map(item => `${item.name}@${item.version}`),
  };
  sections.push(
    '## Machine-readable package manifest',
    `${MANIFEST_HEADER}\n${JSON.stringify(manifest, null, 2)}\n${MANIFEST_FOOTER}`
  );
  const bytes = Buffer.from(`${sections.join('\n\n')}\n`);
  await writeFile(join(root, noticesFileName), bytes);
  console.log(
    `${noticesFileName}: ${packages.length} production package versions, ${textRecords.size} distinct notice texts, ${bytes.length} bytes`
  );
}
