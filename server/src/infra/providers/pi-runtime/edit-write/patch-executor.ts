/**
 * The apply_patch-style multi-file path of the Edit bridge tool: preflight,
 * sequential (non-atomic) execution of add/delete/rename/update operations,
 * and the shared post-patch diagnostics pass. Single-file replacements are
 * delegated back to the Edit tool shell via the injected `runSingleFileEdit`
 * runner, so update operations behave exactly like standalone Edit calls.
 */

import { mkdir, rename, rm, stat } from 'fs/promises';
import * as path from 'path';

import { buildAutoGeneratedMessage, findAutoGeneratedMarker } from '../auto-generated-guard.js';
import { parseApplyPatch } from '../apply-patch.js';
import { buildFileDiff } from '../diff.js';
import { recordFileBackup } from '../file-history.js';
import { runWithFileWriteLock } from '../file-write-lock.js';
import { hashlineForLine } from '../hashline.js';
import { NOOP_EDIT_HARD_LIMIT } from '../noop-edit-guard.js';
import { readTextFileWithMetadata } from '../text-io.js';
import { validateMutationContent } from '../write-guards.js';
import { resolveInsideWorkspace, toWorkspaceRelative } from '../workspace-paths.js';
import {
  buildMutationDetailsBase,
  buildMutationResultText,
  truncateDiffDetail,
} from './mutation-details.js';
import {
  collectDiagnosticsReports,
  mergePerFileLifecycles,
  PatchDiagnosticsTargets,
  runPatchDiagnostics,
} from './patch-diagnostics.js';
import {
  errorResult,
  firstPatchFailurePath,
  resultDetails,
  runWithFileWriteLocks,
  textResult,
  type FileMutationToolOptions,
  type FileMutationToolResult,
  type MutationDetails,
} from './shared.js';
import { createWriteBridgeTool } from './write-tool.js';

/** Runs one single-file Edit (the tool shell's non-patch path). */
export type SingleFileEditRunner = (
  toolCallId: string,
  params: Record<string, unknown>,
  options?: FileMutationToolOptions
) => Promise<FileMutationToolResult>;

export interface PatchExecution {
  cwd: string;
  options: FileMutationToolOptions | undefined;
  toolCallId: string;
  /** Non-empty apply_patch payload (already trimmed-checked by the caller). */
  patch: string;
  previewOnly: boolean;
  runSingleFileEdit: SingleFileEditRunner;
}

export async function executePatch(execution: PatchExecution): Promise<FileMutationToolResult> {
  const { cwd, options, toolCallId, patch, previewOnly, runSingleFileEdit } = execution;
  try {
    const operations = parseApplyPatch(patch);
    const perFileResults: MutationDetails[] = [];
    // Inline diagnostics run once after every operation (see
    // patch-diagnostics.ts); the per-file writes skip their own check.
    const patchDiagnostics =
      !previewOnly && options?.diagnosticsProvider && options.diagnosticsMode !== 'deferred'
        ? { provider: options.diagnosticsProvider, targets: new PatchDiagnosticsTargets() }
        : undefined;
    const operationOptions: FileMutationToolOptions | undefined = patchDiagnostics
      ? { ...options, diagnosticsProvider: undefined }
      : options;
    if (!previewOnly) {
      // Preflight runs with the noop guard disabled: it is a speculative
      // dry run, so failures inside it must not count toward
      // NOOP_EDIT_HARD_LIMIT — only the real run records its own. A
      // failed preflight short-circuits the real run, so record the
      // failed patch once here (keyed by patch content, so an adjusted
      // patch starts fresh) to keep the edit-loop protection intact.
      const preflight = await executePatch({
        cwd,
        options: { ...options, noopGuard: undefined },
        toolCallId: `${toolCallId}:preflight`,
        patch,
        previewOnly: true,
        runSingleFileEdit,
      });
      const preflightDetails = resultDetails(preflight);
      if (preflightDetails.ok === false) {
        const failurePath = firstPatchFailurePath(preflightDetails);
        const attempts = options?.noopGuard
          ? options.noopGuard.record(
              failurePath ? path.resolve(cwd, failurePath) : cwd,
              `patch_failed:${hashlineForLine(patch)}`
            )
          : 0;
        if (attempts >= NOOP_EDIT_HARD_LIMIT) {
          return errorResult(
            'edit_loop_detected',
            `This patch has failed preflight ${attempts} times` +
              (failurePath ? ` (last failure in ${failurePath})` : '') +
              '. Read the file again to see its current content before retrying.',
            {
              ...(failurePath ? { path: failurePath } : {}),
              attempts,
              ...(preflightDetails.perFileResults
                ? { perFileResults: preflightDetails.perFileResults }
                : {}),
            }
          );
        }
        return textResult(
          buildMutationResultText({
            action: 'Patch failed preflight',
            perFileResults: preflightDetails.perFileResults,
            diff: typeof preflightDetails.diff === 'string' ? preflightDetails.diff : undefined,
            snapshotUpdated: false,
          }),
          {
            ...preflightDetails,
            preview: false,
          }
        );
      }
    }
    for (const operation of operations) {
      if (operation.type === 'add') {
        let filePath: string;
        try {
          filePath = resolveInsideWorkspace(cwd, operation.path);
        } catch (err) {
          const failure = {
            ok: false,
            error: 'path_outside_workspace',
            message: err instanceof Error ? err.message : String(err),
            path: operation.path,
            type: 'create',
          };
          if (perFileResults.length === 0) return textResult(failure.message, failure);
          perFileResults.push(failure);
          break;
        }
        const relPath = toWorkspaceRelative(cwd, filePath);
        const contentGuard = validateMutationContent(filePath, operation.content);
        if (contentGuard) {
          const failure = {
            ok: false,
            error: contentGuard.code,
            message: contentGuard.message,
            path: relPath,
            type: 'create',
            ...(contentGuard.details ?? {}),
          };
          if (perFileResults.length === 0) return textResult(failure.message, failure);
          perFileResults.push(failure);
          break;
        }
        const filenameMarker = findAutoGeneratedMarker(filePath, null);
        if (filenameMarker) {
          const failure = {
            ok: false,
            error: 'auto_generated_file',
            message: buildAutoGeneratedMessage(relPath, filenameMarker),
            path: relPath,
            type: 'create',
          };
          if (perFileResults.length === 0) return textResult(failure.message, failure);
          perFileResults.push(failure);
          break;
        }
        let existed = false;
        let originalContent: string | null = null;
        try {
          // Symlinks are followed through to their target by the Write
          // tool (and by resolveWritePath); stat() here follows the link.
          const targetStat = await stat(filePath);
          if (!targetStat.isFile()) {
            const failure = {
              ok: false,
              error: 'not_a_file',
              message: `Path is not a file: ${relPath}`,
              path: relPath,
              type: 'create',
            };
            if (perFileResults.length === 0) return textResult(failure.message, failure);
            perFileResults.push(failure);
            break;
          }
          existed = true;
          const originalMetadata = await readTextFileWithMetadata(filePath);
          originalContent = originalMetadata.content;
          const generatedMarker = findAutoGeneratedMarker(filePath, originalContent);
          if (generatedMarker) {
            const failure = {
              ok: false,
              error: 'auto_generated_file',
              message: buildAutoGeneratedMessage(relPath, generatedMarker),
              path: relPath,
              type: 'create',
            };
            if (perFileResults.length === 0) return textResult(failure.message, failure);
            perFileResults.push(failure);
            break;
          }
          const readCheck = await options?.readFileState?.assertSafeToWrite(
            filePath,
            originalContent
          );
          if (readCheck && !readCheck.ok) {
            const failure = {
              ok: false,
              error: readCheck.code,
              message: readCheck.message,
              path: relPath,
              type: 'create',
            };
            if (perFileResults.length === 0) return textResult(failure.message, failure);
            perFileResults.push(failure);
            break;
          }
        } catch (err) {
          if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
        }
        if (previewOnly) {
          const diff = buildFileDiff(relPath, originalContent ?? '', operation.content);
          perFileResults.push({
            ...buildMutationDetailsBase({
              path: relPath,
              diff,
              extra: {
                preview: true,
                type: existed ? 'update' : 'create',
              },
            }),
            preview: true,
            type: existed ? 'update' : 'create',
            path: relPath,
          });
          continue;
        }
        patchDiagnostics?.targets.add({
          // Matches the perFileResults entry below.
          path: operation.path,
          absolutePath: filePath,
          originalContent,
        });
        const writeTool = createWriteBridgeTool(cwd, operationOptions);
        const result = await writeTool.execute(`${toolCallId}:add:${operation.path}`, {
          file_path: operation.path,
          content: operation.content,
        });
        const details = resultDetails(result);
        if (details.ok === false) {
          if (perFileResults.length === 0) return result;
          perFileResults.push({ ...details, path: operation.path });
          break;
        }
        perFileResults.push({ ...details, path: operation.path });
        continue;
      }
      if (operation.type === 'delete') {
        const filePath = resolveInsideWorkspace(cwd, operation.path);
        const originalMetadata = await readTextFileWithMetadata(filePath);
        const original = originalMetadata.content;
        const generatedMarker = findAutoGeneratedMarker(filePath, original);
        if (generatedMarker) {
          const message = buildAutoGeneratedMessage(operation.path, generatedMarker);
          const failure = {
            ok: false,
            error: 'auto_generated_file',
            message,
            path: operation.path,
            type: 'delete',
          };
          if (perFileResults.length === 0) return textResult(message, failure);
          perFileResults.push(failure);
          break;
        }
        const readCheck = await options?.readFileState?.assertSafeToWrite(filePath, original);
        if (readCheck && !readCheck.ok) {
          const failure = {
            ok: false,
            error: readCheck.code,
            message: readCheck.message,
            path: operation.path,
            type: 'delete',
          };
          if (perFileResults.length === 0) return textResult(readCheck.message, failure);
          perFileResults.push(failure);
          break;
        }
        const diff = buildFileDiff(operation.path, original, '');
        const backup = previewOnly
          ? undefined
          : await recordFileBackup(operation.path, original, filePath);
        if (!previewOnly) {
          await runWithFileWriteLock(filePath, async () => {
            await rm(filePath);
          });
          options?.noopGuard?.clear(filePath);
        }
        perFileResults.push({
          ...buildMutationDetailsBase({
            path: operation.path,
            diff,
            extra: {
              ...(previewOnly ? { preview: true } : {}),
              type: 'delete',
              ...(backup ? { backup } : {}),
            },
          }),
          ...(previewOnly ? { preview: true } : {}),
          type: 'delete',
          path: operation.path,
          ...(backup ? { backup } : {}),
        });
        continue;
      }
      if (operation.type === 'rename') {
        const fromPath = resolveInsideWorkspace(cwd, operation.from);
        const toPath = resolveInsideWorkspace(cwd, operation.to);
        try {
          await stat(toPath);
          const failure = {
            ok: false,
            error: 'target_exists',
            message: `Rename target already exists: ${operation.to}`,
            path: operation.to,
            originalPath: operation.from,
            type: 'rename',
          };
          if (perFileResults.length === 0) return textResult(failure.message, failure);
          perFileResults.push(failure);
          break;
        } catch {
          // Target does not exist, so rename is allowed.
        }
        const originalMetadata = await readTextFileWithMetadata(fromPath);
        const original = originalMetadata.content;
        const generatedMarker = findAutoGeneratedMarker(fromPath, original);
        if (generatedMarker) {
          const message = buildAutoGeneratedMessage(operation.from, generatedMarker);
          const failure = {
            ok: false,
            error: 'auto_generated_file',
            message,
            path: operation.to,
            originalPath: operation.from,
            type: 'rename',
          };
          if (perFileResults.length === 0) return textResult(message, failure);
          perFileResults.push(failure);
          break;
        }
        const readCheck = await options?.readFileState?.assertSafeToWrite(fromPath, original);
        if (readCheck && !readCheck.ok) {
          const failure = {
            ok: false,
            error: readCheck.code,
            message: readCheck.message,
            path: operation.to,
            originalPath: operation.from,
            type: 'rename',
          };
          if (perFileResults.length === 0) return textResult(readCheck.message, failure);
          perFileResults.push(failure);
          break;
        }
        const backup = previewOnly
          ? undefined
          : await recordFileBackup(operation.from, original, fromPath);
        if (!previewOnly) {
          await runWithFileWriteLocks([fromPath, toPath], async () => {
            await mkdir(path.dirname(toPath), { recursive: true });
            await rename(fromPath, toPath);
          });
          await options?.readFileState?.recordWrite(toPath, original);
          options?.noopGuard?.clear(fromPath);
          options?.noopGuard?.clear(toPath);
        }
        perFileResults.push({
          ok: true,
          ...(previewOnly ? { preview: true } : {}),
          type: 'rename',
          path: operation.to,
          originalPath: operation.from,
          updatedContent: original,
          ...(backup ? { backup } : {}),
        });
        continue;
      }
      if (patchDiagnostics) {
        try {
          const targetPath = resolveInsideWorkspace(cwd, operation.path);
          await patchDiagnostics.targets.addFromDisk(operation.path, targetPath);
        } catch {
          // Outside the workspace: the update reports the failure.
        }
      }
      const runUpdate = (oldText: string, newText: string, attempt: string) =>
        runSingleFileEdit(
          `${toolCallId}:update:${operation.path}${attempt}`,
          {
            file_path: operation.path,
            old_string: oldText,
            new_string: newText,
            ...(previewOnly ? { preview_only: true } : {}),
          },
          operationOptions
        );
      let result = await runUpdate(operation.oldText, operation.newText, '');
      {
        const failed = resultDetails(result);
        // The parser always emits newline-terminated oldText/newText, so
        // a hunk anchored at EOF of a file without a trailing newline can
        // never match. Retry with the trailing newline dropped — only
        // when the target file itself ends without one, so mid-file
        // matches are unaffected.
        if (failed.ok === false && failed.error === 'not_found') {
          try {
            const targetPath = resolveInsideWorkspace(cwd, operation.path);
            const targetMetadata = await readTextFileWithMetadata(targetPath);
            if (!targetMetadata.content.endsWith('\n')) {
              result = await runUpdate(
                operation.oldText.replace(/\n$/, ''),
                operation.newText.replace(/\n$/, ''),
                ':no-trailing-newline'
              );
            }
          } catch {
            // Target unreadable or missing — keep the original failure.
          }
        }
      }
      const details = resultDetails(result);
      if (details.ok === false) {
        if (perFileResults.length === 0) return result;
        perFileResults.push({ ...details, type: 'update', path: operation.path });
        break;
      }
      perFileResults.push({ ...details, type: 'update', path: operation.path });
    }
    if (patchDiagnostics) {
      await runPatchDiagnostics(
        patchDiagnostics.provider,
        patchDiagnostics.targets.list(),
        perFileResults
      );
    }
    const diagnosticsReports = collectDiagnosticsReports(perFileResults);
    const lifecycle = mergePerFileLifecycles(perFileResults);
    const failed = perFileResults.some(result => result.ok === false);
    const patchDiff = perFileResults
      .map(result => result.diff)
      .filter((diff): diff is string => typeof diff === 'string' && diff.length > 0)
      .join('\n');
    const patchDiffDetails = truncateDiffDetail(patchDiff);
    if (failed) {
      return textResult(
        buildMutationResultText({
          action: 'Patch partially failed',
          perFileResults,
          diff: patchDiff,
          snapshotUpdated: false,
          diagnosticsReports,
        }),
        {
          ok: false,
          error: 'patch_partial_failure',
          perFileResults,
          ...(patchDiff ? { diff: patchDiffDetails.diff } : {}),
          ...(patchDiffDetails.truncated ? { diffTruncated: true } : {}),
          ...(lifecycle ? { lifecycle } : {}),
        }
      );
    }
    return textResult(
      buildMutationResultText({
        action: previewOnly ? 'Previewed patch' : 'Applied patch',
        fileCount: perFileResults.length,
        perFileResults,
        diff: patchDiff,
        firstChangedLine: perFileResults.find(result => result.firstChangedLine !== undefined)
          ?.firstChangedLine,
        preview: previewOnly,
        snapshotUpdated: false,
        diagnosticsReports,
      }),
      {
        ok: true,
        ...(previewOnly ? { preview: true } : {}),
        perFileResults,
        diff: patchDiffDetails.diff,
        ...(patchDiffDetails.truncated ? { diffTruncated: true } : {}),
        firstChangedLine: perFileResults.find(result => result.firstChangedLine !== undefined)
          ?.firstChangedLine,
        ...(lifecycle ? { lifecycle } : {}),
      }
    );
  } catch (err) {
    return errorResult('patch_failed', err instanceof Error ? err.message : String(err));
  }
}
