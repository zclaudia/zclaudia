/**
 * The Edit bridge tool shell: parameter schema, argument parsing, and the
 * dispatch across the three single-file paths (batch / hashline / exact).
 * The patch path lives in patch-executor.ts, the pure read-guard/match/apply
 * logic in edit-core.ts, and the shared backup→atomic-write→recordWrite→
 * lifecycle tail in persist-mutation.ts.
 */

import type { AgentTool } from '@earendil-works/pi-agent-core';
import { stat } from 'fs/promises';
import * as path from 'path';

import { buildAutoGeneratedMessage, findAutoGeneratedMarker } from '../auto-generated-guard.js';
import { buildFileDiff } from '../diff.js';
import { buildMutationStateDescriptor } from '../file-state.js';
import { runWithFileWriteLock } from '../file-write-lock.js';
import {
  hashlineForLine,
  hashlineTag,
  parseHashlineOperation,
} from '../hashline.js';
import { NOOP_EDIT_HARD_LIMIT } from '../noop-edit-guard.js';
import { readTextFileWithMetadata } from '../text-io.js';
import { MAX_EDIT_FILE_BYTES, validateMutationContent } from '../write-guards.js';
import { resolveInsideWorkspace, toWorkspaceRelative } from '../workspace-paths.js';
import {
  applyBatchEdits,
  applyExactEdit,
  applyHashlineEdit,
  createStaleRebaseFailure,
  detectHashlineTagDrift,
  evaluateReadGuard,
  hashlineMismatchError,
} from './edit-core.js';
import { buildMutationDetailsBase, buildMutationResultText } from './mutation-details.js';
import { executePatch, type SingleFileEditRunner } from './patch-executor.js';
import { persistMutation } from './persist-mutation.js';
import {
  assertRebaseAnchorsWereRead,
  errorResult,
  guardErrorDetails,
  parseBatchEdits,
  resolveWritePath,
  textResult,
  toolParams,
  validateUpdatedContent,
  type FileMutationToolOptions,
  type FileMutationToolResult,
} from './shared.js';

export function createEditBridgeTool(cwd: string, options?: FileMutationToolOptions): AgentTool {
  const runSingleFileEdit: SingleFileEditRunner = (toolCallId, params, runOptions) =>
    executeSingleFileEdit({
      cwd,
      options: runOptions ?? options,
      args: toolParams(toolCallId, params),
    });
  return {
    name: 'Edit',
    label: 'Edit',
    description:
      'Replace one exact string in an existing file. For two or more replacements in the same file, use MultiEdit so the file is read, checked, and written once; the batch is atomic and counts as one mutation attempt. This tool still accepts an `edits` array for compatibility, but new same-file batches should prefer MultiEdit. For small multi-file changes, use `patch`. For structurally-sensitive rewrites (Markdown tables, JSON arrays, indented YAML/TOML), prefer a single Write. Successful mutation results include a model-visible diff plus snapshot state, and update the internal file snapshot, so do not call Read again only to verify the edit.',
    parameters: {
      type: 'object',
      properties: {
        file_path: {
          type: 'string',
          description:
            'Workspace-relative path of the file to edit (required unless `patch` is given)',
        },
        old_string: {
          type: 'string',
          description:
            'Exact text to replace (required unless `patch` or `hashline_operation` is given)',
        },
        new_string: {
          type: 'string',
          description: 'Replacement text (required unless `patch` is given)',
        },
        replace_all: { type: 'boolean', default: false },
        edits: {
          type: 'array',
          description:
            'Compatibility path for same-file batch replacements. Prefer MultiEdit for two or more replacements in one file; all replacements apply atomically and consume one mutation attempt.',
          minItems: 1,
          items: {
            type: 'object',
            properties: {
              old_string: { type: 'string' },
              new_string: { type: 'string' },
              replace_all: { type: 'boolean', default: false },
            },
            required: ['old_string', 'new_string'],
          },
        },
        patch: {
          type: 'string',
          description:
            'Optional apply_patch-style multi-file patch. When provided, file_path/old_string/new_string are ignored. Operations apply sequentially and are NOT atomic: a failure partway leaves earlier operations already written to disk (reported as patch_partial_failure). Real runs are preflighted automatically; pass preview_only:true for an explicit dry run before a risky patch.',
        },
        preview_only: {
          type: 'boolean',
          default: false,
          description:
            'When true, validate the edit and compute the diff without writing to disk or updating the snapshot (dry run).',
        },
        hashline_line: {
          type: 'string',
          description: 'Optional line hash from Read(hashline:true)',
        },
        hashline_operation: {
          type: 'string',
          description: 'Optional hashline operation, such as replace:<line-hash>',
        },
        hashline_tag: {
          type: 'string',
          description: 'Optional file-level tag from Read(hashline:true)',
        },
      },
    },
    execute: async (toolCallId: string, params: unknown) => {
      const args = toolParams(toolCallId, params);
      if (typeof args.patch === 'string' && args.patch.trim()) {
        return executePatch({
          cwd,
          options,
          toolCallId,
          patch: args.patch,
          previewOnly: args.preview_only === true,
          runSingleFileEdit,
        });
      }
      return runSingleFileEdit(toolCallId, args);
    },
  } as unknown as AgentTool;
}

interface SingleFileEditExecution {
  cwd: string;
  options: FileMutationToolOptions | undefined;
  args: Record<string, unknown>;
}

async function executeSingleFileEdit(
  execution: SingleFileEditExecution
): Promise<FileMutationToolResult> {
  const { cwd, options, args } = execution;
  const requested = args.file_path;
  if (typeof requested !== 'string' || !requested.trim()) {
    return errorResult('missing_path', 'Edit requires file_path');
  }
  const batchEditsResult = parseBatchEdits(args.edits);
  if (batchEditsResult?.ok === false) {
    return errorResult(
      batchEditsResult.code,
      batchEditsResult.message,
      batchEditsResult.details ?? {}
    );
  }
  const batchEdits = batchEditsResult?.ok === true ? batchEditsResult.edits : undefined;
  const hashlineOperation = parseHashlineOperation(args.hashline_operation);
  const hashlineLine =
    hashlineOperation?.hash ??
    (typeof args.hashline_line === 'string' ? args.hashline_line.trim() : '');
  const isHashlineEdit = Boolean(hashlineLine);
  if (batchEdits && isHashlineEdit) {
    return errorResult(
      'invalid_edit_mode',
      'Edit cannot combine edits with hashline_operation/hashline_line'
    );
  }
  if (
    !isHashlineEdit &&
    !batchEdits &&
    (typeof args.old_string !== 'string' || typeof args.new_string !== 'string')
  ) {
    return errorResult('missing_strings', 'Edit requires old_string and new_string');
  }
  if (!isHashlineEdit && !batchEdits && args.old_string === args.new_string) {
    return errorResult('no_op', 'old_string and new_string are identical');
  }
  if (!batchEdits && typeof args.new_string !== 'string') {
    return errorResult('missing_strings', 'Edit requires new_string');
  }
  const newString = typeof args.new_string === 'string' ? args.new_string : '';
  const oldString = typeof args.old_string === 'string' ? args.old_string : '';
  const replaceAll = args.replace_all === true;
  let filePath: string;
  try {
    filePath = resolveInsideWorkspace(cwd, requested);
  } catch (err) {
    return errorResult('path_outside_workspace', err instanceof Error ? err.message : String(err));
  }
  const replacementGuard = batchEdits
    ? batchEdits
        .map((edit, index) => ({
          index,
          guard: validateMutationContent(filePath, edit.newString),
        }))
        .find(entry => entry.guard)
    : { index: undefined, guard: validateMutationContent(filePath, newString) };
  if (replacementGuard?.guard) {
    return errorResult(
      replacementGuard.guard.code,
      replacementGuard.guard.message,
      guardErrorDetails(replacementGuard.guard, {
        path: toWorkspaceRelative(cwd, filePath),
        ...(replacementGuard.index !== undefined ? { editIndex: replacementGuard.index } : {}),
      })
    );
  }
  try {
    return await runWithFileWriteLock(filePath, async () => {
      const relPathForChecks = toWorkspaceRelative(cwd, filePath);
      const targetResult = await resolveWritePath(cwd, filePath, relPathForChecks);
      if (!targetResult.ok) return targetResult.result;
      const writePath = targetResult.writePath;
      const fileStat = await stat(filePath); // follows the symlink to its target
      if (!fileStat.isFile()) {
        return errorResult('not_a_file', `Path is not a file: ${relPathForChecks}`);
      }
      if (fileStat.size > MAX_EDIT_FILE_BYTES) {
        return errorResult(
          'file_too_large',
          `File is too large to edit safely: ${relPathForChecks}`,
          {
            path: relPathForChecks,
            size: fileStat.size,
            maxSize: MAX_EDIT_FILE_BYTES,
          }
        );
      }
      if (path.extname(filePath).toLowerCase() === '.ipynb') {
        return errorResult(
          'unsupported_notebook_edit',
          'Jupyter notebooks require a notebook-aware edit tool.',
          {
            path: relPathForChecks,
          }
        );
      }
      const originalMetadata = await readTextFileWithMetadata(filePath);
      const original = originalMetadata.content;
      const generatedMarker = findAutoGeneratedMarker(filePath, original);
      if (generatedMarker) {
        const relPath = toWorkspaceRelative(cwd, filePath);
        return errorResult(
          'auto_generated_file',
          buildAutoGeneratedMessage(relPath, generatedMarker),
          { path: relPath }
        );
      }
      const hashlineTagDrift = isHashlineEdit
        ? detectHashlineTagDrift(original, args.hashline_tag)
        : false;
      const readEntry = options?.readFileState?.get(filePath);
      const readCheck = isHashlineEdit
        ? options?.readFileState?.assertEditableHashline(filePath)
        : options?.readFileState?.assertEditable(filePath, original);
      const guardDecision = evaluateReadGuard({
        readCheck,
        isHashlineEdit,
        relPath: relPathForChecks,
        currentContent: original,
        readEntry,
      });
      if (!guardDecision.proceed) return guardDecision.result;
      const rebased = guardDecision.rebased;
      const staleRebaseFailure = createStaleRebaseFailure({
        rebased,
        relPath: relPathForChecks,
        currentContent: original,
        readEntry,
      });
      if (rebased) {
        const rebaseAnchorCheck = assertRebaseAnchorsWereRead(
          readEntry?.content,
          batchEdits ?? [{ oldString, newString, replaceAll }]
        );
        if (!rebaseAnchorCheck.ok) {
          return staleRebaseFailure(
            rebaseAnchorCheck.code,
            rebaseAnchorCheck.message,
            rebaseAnchorCheck.details
          );
        }
      }
      if (batchEdits) {
        const relPath = toWorkspaceRelative(cwd, filePath);
        const applied = applyBatchEdits(original, batchEdits);
        if (!applied.ok) {
          if (applied.kind === 'not_found') {
            const attempts =
              options?.noopGuard?.record(
                filePath,
                `batch_not_found:${applied.index}:${hashlineForLine(applied.oldString)}`
              ) ?? 0;
            if (attempts >= NOOP_EDIT_HARD_LIMIT) {
              return errorResult(
                'edit_loop_detected',
                `This batch edit has failed ${attempts} times — edits[${applied.index}].old_string does not exist in ${relPath}. ` +
                  'Read the file again to see its current content before retrying.',
                { path: relPath, editIndex: applied.index, attempts }
              );
            }
            return staleRebaseFailure(
              'not_found',
              `edits[${applied.index}].old_string not found in file`,
              { path: relPath, editIndex: applied.index }
            );
          }
          if (applied.matchedAfterNormalization) {
            return staleRebaseFailure(
              'not_unique',
              `edits[${applied.index}].old_string matches ${applied.occurrences} locations after whitespace-normalization; add more surrounding context`,
              { path: relPath, editIndex: applied.index, occurrences: applied.occurrences }
            );
          }
          return staleRebaseFailure(
            'not_unique',
            `edits[${applied.index}].old_string appears ${applied.occurrences} times; pass replace_all:true or add more context`,
            {
              path: relPath,
              editIndex: applied.index,
              occurrences: applied.occurrences,
            }
          );
        }
        const { updated, totalReplaced, appliedEdits } = applied;
        if (updated === original) {
          const attempts =
            options?.noopGuard?.record(filePath, `batch_noop:${batchEdits.length}`) ?? 0;
          if (attempts >= NOOP_EDIT_HARD_LIMIT) {
            return errorResult(
              'edit_loop_detected',
              `This batch edit leaves ${relPath} unchanged and has been repeated ${attempts} times. ` +
                'Read the file — the change may already be in place.',
              { path: relPath, attempts }
            );
          }
          return errorResult('no_op', 'Batch edits leave the file unchanged', {
            path: relPath,
          });
        }

        const updatedGuard = validateUpdatedContent(filePath, updated, { path: relPath });
        if (!updatedGuard.ok) return updatedGuard.result;
        const diff = buildFileDiff(relPath, original, updated);
        const state = buildMutationStateDescriptor({
          relPath,
          originalContent: original,
          updatedContent: updated,
          diff,
          snapshotUpdated: args.preview_only !== true,
          readSnapshotContent: rebased ? readEntry?.content : undefined,
          rebased,
        });
        const detailsBase = buildMutationDetailsBase({
          path: relPath,
          diff,
          extra: {
            replaced: totalReplaced,
            editCount: batchEdits.length,
            edits: appliedEdits,
            state,
            ...(rebased ? { rebased: true } : {}),
          },
        });
        if (args.preview_only === true) {
          return textResult(
            buildMutationResultText({
              action: 'Previewed edit',
              path: relPath,
              replaced: totalReplaced,
              editCount: batchEdits.length,
              diff: diff.diff,
              firstChangedLine: diff.firstChangedLine,
              lineChanges: diff.lineChanges,
              preview: true,
              snapshotUpdated: false,
              state,
              rebased,
            }),
            {
              ...detailsBase,
              preview: true,
            }
          );
        }

        const { backup, lifecycle } = await persistMutation({
          options,
          relPath,
          filePath,
          writePath,
          original,
          updated,
          originalMetadata,
          diff,
          clearNoopGuard: true,
        });
        return textResult(
          buildMutationResultText({
            action: 'Edited',
            path: relPath,
            replaced: totalReplaced,
            editCount: batchEdits.length,
            diff: diff.diff,
            firstChangedLine: diff.firstChangedLine,
            lineChanges: diff.lineChanges,
            state,
            rebased,
            diagnostics: lifecycle?.diagnosticsReport,
          }),
          {
            ...detailsBase,
            backup,
            ...(lifecycle ? { lifecycle } : {}),
          }
        );
      }

      if (isHashlineEdit) {
        // The snapshot (file as the model last saw it) disambiguates duplicate lines.
        const snapshot = options?.readFileState?.get(filePath)?.content;
        const updated = applyHashlineEdit(original, hashlineLine, newString, snapshot);
        const relPath = toWorkspaceRelative(cwd, filePath);
        if (updated === undefined) {
          const attempts =
            options?.noopGuard?.record(filePath, `hashline_mismatch:${hashlineLine}`) ?? 0;
          if (attempts >= NOOP_EDIT_HARD_LIMIT) {
            return errorResult(
              'edit_loop_detected',
              `This hashline edit has failed ${attempts} times — the anchored line no longer exists in ${relPath}. ` +
                'Read the file again with hashline:true to get fresh anchors.',
              { path: relPath, attempts }
            );
          }
          return hashlineMismatchError({
            relPath,
            tagDrift: hashlineTagDrift,
            currentContent: original,
            readEntry,
          });
        }
        const updatedGuard = validateUpdatedContent(filePath, updated, { path: relPath });
        if (!updatedGuard.ok) return updatedGuard.result;
        const diff = buildFileDiff(relPath, original, updated);
        const state = buildMutationStateDescriptor({
          relPath,
          originalContent: original,
          updatedContent: updated,
          diff,
          snapshotUpdated: args.preview_only !== true,
          readSnapshotContent: hashlineTagDrift ? readEntry?.content : undefined,
          rebased: hashlineTagDrift,
        });
        const hashlineDetailsBase = buildMutationDetailsBase({
          path: relPath,
          diff,
          extra: {
            replaced: 1,
            state,
            ...(hashlineTagDrift ? { rebased: true } : {}),
          },
        });
        if (args.preview_only === true) {
          return textResult(
            buildMutationResultText({
              action: 'Previewed edit',
              path: relPath,
              replaced: 1,
              diff: diff.diff,
              firstChangedLine: diff.firstChangedLine,
              lineChanges: diff.lineChanges,
              preview: true,
              snapshotUpdated: false,
              state,
              rebased: hashlineTagDrift,
            }),
            {
              ...hashlineDetailsBase,
              preview: true,
              hashline: {
                tag: hashlineTag(original),
                ...(hashlineTagDrift ? { tagDrift: true } : {}),
              },
            }
          );
        }
        if (updated === original) {
          const attempts = options?.noopGuard?.record(filePath, `noop:${hashlineLine}`) ?? 0;
          if (attempts >= NOOP_EDIT_HARD_LIMIT) {
            return errorResult(
              'edit_loop_detected',
              `This edit leaves ${relPath} unchanged and has been repeated ${attempts} times. ` +
                'Read the file — the change may already be in place.',
              { path: relPath, attempts }
            );
          }
        } else {
          options?.noopGuard?.clear(filePath);
        }
        const { backup, lifecycle } = await persistMutation({
          options,
          relPath,
          filePath,
          writePath,
          original,
          updated,
          originalMetadata,
          diff,
          // The guard was already recorded or cleared above.
          clearNoopGuard: false,
        });
        return textResult(
          buildMutationResultText({
            action: 'Edited',
            path: relPath,
            replaced: 1,
            diff: diff.diff,
            firstChangedLine: diff.firstChangedLine,
            lineChanges: diff.lineChanges,
            state,
            rebased: hashlineTagDrift,
            diagnostics: lifecycle?.diagnosticsReport,
          }),
          {
            ...hashlineDetailsBase,
            hashline: {
              tag: hashlineTag(updated),
              ...(hashlineTagDrift ? { tagDrift: true } : {}),
            },
            backup,
            ...(lifecycle ? { lifecycle } : {}),
          }
        );
      }
      const applied = applyExactEdit(original, oldString, newString, replaceAll);
      if (!applied.ok) {
        const relPathNF = toWorkspaceRelative(cwd, filePath);
        if (applied.kind === 'not_found') {
          const attempts =
            options?.noopGuard?.record(filePath, `not_found:${hashlineForLine(applied.oldString)}`) ??
            0;
          if (attempts >= NOOP_EDIT_HARD_LIMIT) {
            return errorResult(
              'edit_loop_detected',
              `This exact edit has failed ${attempts} times — old_string does not exist in ${relPathNF}. ` +
                'Read the file again to see its current content before retrying.',
              { path: relPathNF, attempts }
            );
          }
          return staleRebaseFailure('not_found', 'old_string not found in file', {
            path: relPathNF,
          });
        }
        if (applied.matchedAfterNormalization) {
          return staleRebaseFailure(
            'not_unique',
            `old_string matches ${applied.occurrences} locations after whitespace-normalization; add more surrounding context`,
            { path: relPathNF, occurrences: applied.occurrences }
          );
        }
        return staleRebaseFailure(
          'not_unique',
          `old_string appears ${applied.occurrences} times; pass replace_all:true or add more context`,
          {
            path: toWorkspaceRelative(cwd, filePath),
            occurrences: applied.occurrences,
          }
        );
      }
      const { updated, replaced, matchStrategy } = applied;
      const relPath = toWorkspaceRelative(cwd, filePath);
      const updatedGuard = validateUpdatedContent(filePath, updated, { path: relPath });
      if (!updatedGuard.ok) return updatedGuard.result;
      const diff = buildFileDiff(relPath, original, updated);
      const state = buildMutationStateDescriptor({
        relPath,
        originalContent: original,
        updatedContent: updated,
        diff,
        snapshotUpdated: args.preview_only !== true,
        readSnapshotContent: rebased ? readEntry?.content : undefined,
        rebased,
      });
      const detailsBase = buildMutationDetailsBase({
        path: relPath,
        diff,
        extra: {
          replaced,
          state,
          ...(rebased ? { rebased: true } : {}),
        },
      });
      if (args.preview_only === true) {
        return textResult(
          buildMutationResultText({
            action: 'Previewed edit',
            path: relPath,
            replaced,
            diff: diff.diff,
            firstChangedLine: diff.firstChangedLine,
            lineChanges: diff.lineChanges,
            preview: true,
            snapshotUpdated: false,
            state,
            rebased,
          }),
          {
            ...detailsBase,
            matchStrategy,
            preview: true,
          }
        );
      }
      const { backup, lifecycle } = await persistMutation({
        options,
        relPath,
        filePath,
        writePath,
        original,
        updated,
        originalMetadata,
        diff,
        clearNoopGuard: updated !== original,
      });
      return textResult(
        buildMutationResultText({
          action: 'Edited',
          path: relPath,
          replaced,
          diff: diff.diff,
          firstChangedLine: diff.firstChangedLine,
          lineChanges: diff.lineChanges,
          state,
          rebased,
          diagnostics: lifecycle?.diagnosticsReport,
        }),
        {
          ...detailsBase,
          matchStrategy,
          backup,
          ...(lifecycle ? { lifecycle } : {}),
        }
      );
    });
  } catch (err) {
    return errorResult('edit_failed', err instanceof Error ? err.message : String(err), {
      path: String(requested),
    });
  }
}
